"""Generate full-baked.css: the two images only the Full tier needs, with the
hue drift and the over-bright breathe baked in instead of run as live filters.

    python -I gen_full.py <out.css>

Full puts back the glow's hue drift and a sky breathe that goes above full
brightness. As live CSS filters they cost a compositing pass on every frame:
- brightness() on the sky layer: a pass over the whole window.
- hue-rotate() on the glow, which is also screen-blended: either one alone
  Chrome folds into drawing the layer, both together need an extra pass over
  a layer larger than the window.
Measured in headless Chrome at 3456x1408 (tools/perf_theme.mjs), each cost
about as much as the flares; baked, neither costs anything measurable.

- Sky: the art is an indexed PNG, so brightening it is scaling its palette by
  BRIGHT. The breathe then animates opacity over the black page from
  0.8 / BRIGHT to 1, which matches brightness(0.8) to brightness(1.12) except
  in the few colours the scaling clips (at most about 9% darker, at the dim
  end of the breathe).
- Glow: glow.css's baked WebP inside an SVG that applies hue-rotate() to it
  when the image is drawn, stepped HUE_FPS times a second (so the layer is
  redrawn that often, rather than filtered on every frame). The drift is at
  most about 2 degrees a second, so the steps don't show. This replaces
  glow.css in the Full build. Like the ocean's, this animation ignores the
  page's animation:none, so under prefers-reduced-motion the glow stops
  moving but its colour still drifts (a media query inside the SVG doesn't
  see the page's setting).
"""
import base64
import os
import re
import struct
import sys
import urllib.parse
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from step_motion import stepped_keyframes  # noqa: E402

BRIGHT = 1.12        # top of the sky breathe
HUE = (-16, 24)      # glow hue drift, degrees
HUE_T = 37           # seconds from one end of the drift to the other
HUE_FPS = 2          # hue steps a second inside the SVG

base_css = open(os.path.join(HERE, "base", "nyx.json"), encoding="utf-8").read()
art = base64.b64decode(re.search(r"--a:\s*url\(data:image/png;base64,([A-Za-z0-9+/=]+)\)", base_css).group(1))


def brighten(png, k):
    """The PNG with its palette scaled by k; the pixels are untouched."""
    i = png.find(b"PLTE") - 4
    assert i > 0, "the sky art is no longer an indexed PNG"
    n = struct.unpack(">I", png[i:i + 4])[0]
    pal = bytes(min(255, round(c * k)) for c in png[i + 8:i + 8 + n])
    return png[:i + 8] + pal + struct.pack(">I", zlib.crc32(b"PLTE" + pal)) + png[i + 12 + n:]


glow_uri = re.search(r"url\((data:image/webp;base64,[A-Za-z0-9+/=]+)\)",
                     open(os.path.join(HERE, "glow.css"), encoding="utf-8").read()).group(1)
webp = base64.b64decode(glow_uri.split(",", 1)[1])
assert webp[12:16] == b"VP8X", "glow.css's image is not an extended WebP"
gw, gh = (1 + int.from_bytes(webp[a:a + 3], "little") for a in (24, 27))

# Steps land half a step off the grid, between display frames (see step_motion.py).
hue_style = (f"image{{animation:h {HUE_T}s linear {-0.5 / HUE_FPS:g}s infinite alternate}}@keyframes h{{"
             + stepped_keyframes({"filter": [(0, f"hue-rotate({HUE[0]}deg)"), (1, f"hue-rotate({HUE[1]}deg)")]},
                                 HUE_T, "ease-in-out", HUE_FPS, 3)
             + "}")
svg = (f"<svg xmlns='http://www.w3.org/2000/svg' width='{gw}' height='{gh}' viewBox='0 0 {gw} {gh}'>"
       f"<style>{hue_style}</style><image width='{gw}' height='{gh}' href='{glow_uri}'/></svg>")

css = f"""
/* Full tier images, generated by gen_full.py: the sky art brightened by
   {BRIGHT:g} (palette only) and the glow wrapped in an SVG that drifts its hue. */
.dark [data-slot="sidebar-wrapper"]::before {{
  background-image: var(--g), url(data:image/png;base64,{base64.b64encode(brighten(art, BRIGHT)).decode()});
  animation: nyx-base-breathe-full 17s cubic-bezier(0.45, 0, 0.55, 1) infinite alternate;
}}

@keyframes nyx-base-breathe-full {{
  from {{ opacity: {0.8 / BRIGHT:.4f}; }}
  to {{ opacity: 1; }}
}}

.dark [data-slot="sidebar"][data-side="left"]::before {{
  background-image: url("data:image/svg+xml,{urllib.parse.quote(svg, safe=" =:/'.,-;()+")}");
}}
"""
open(sys.argv[1], "w", encoding="utf-8").write(css)
print(f"wrote {sys.argv[1]}: css {len(css)} chars")
